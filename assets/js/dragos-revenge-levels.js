  function padRows(rows) {
    return rows.map((row, idx) => {
      let s = row;
      const isBorder = idx === 0 || idx === rows.length - 1;
      if (s.length > W) s = s.slice(0, W);
      while (s.length < W) s += isBorder ? "#" : ".";
      if (!isBorder) {
        if (s[0] !== "#") s = `#${s.slice(1)}`;
        if (s[W - 1] !== "#") s = `${s.slice(0, W - 1)}#`;
      }
      return s;
    });
  }

